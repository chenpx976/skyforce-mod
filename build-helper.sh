#!/usr/bin/env bash
# 编译 SkyForceTweaks.dll（net35 / mono 2.0 profile，游戏是 Unity 5.5）。
# 需要 mono 的 mcs 以及 assets/ 下的 UnityEngine.dll、Assembly-CSharp.dll.orig。
set -euo pipefail

cd "$(dirname "$0")"

MCS="${MCS:-$(command -v mcs || echo /Library/Frameworks/Mono.framework/Versions/Current/bin/mcs)}"
[ -x "$MCS" ] || { echo "找不到 mcs（mono 未安装？）" >&2; exit 1; }

[ -f assets/UnityEngine.dll ] || { echo "缺少 assets/UnityEngine.dll，先跑 ./fetch.sh" >&2; exit 1; }
[ -f assets/Assembly-CSharp.dll.orig ] || { echo "缺少 assets/Assembly-CSharp.dll.orig，先跑 ./fetch.sh" >&2; exit 1; }

mkdir -p build

# 从 config.json 生成编译期常量（JSON 带注释，用正则提取这一段）
python3 - <<'GEN'
import re

text = open('config.json', encoding='utf-8').read()
block = re.search(r'"revive"\s*:\s*\{(.*?)\}', text, re.S)
body = block.group(1) if block else ''
enabled = re.search(r'"enabled"\s*:\s*(true|false)', body)
per_stage = re.search(r'"perStage"\s*:\s*(\d+)', body)

open('tools/Helper/GeneratedConfig.cs', 'w', encoding='utf-8').write(
    '// <auto-generated> by build-helper.sh from config.json. Do not edit.\n'
    'namespace SkyForceTweaks\n'
    '{\n'
    '    internal static class GeneratedConfig\n'
    '    {\n'
    '        public const bool ReviveEnabled = %s;\n'
    '        public const int RevivesPerStage = %s;\n'
    '    }\n'
    '}\n' % (enabled.group(1) if enabled else 'true', per_stage.group(1) if per_stage else '3')
)
GEN

"$MCS" -sdk:2.0 -target:library -warn:0 \
  -out:build/SkyForceTweaks.dll \
  -r:assets/Assembly-CSharp.dll.orig \
  -r:assets/UnityEngine.dll \
  tools/Helper/*.cs

echo "→ build/SkyForceTweaks.dll ($(wc -c < build/SkyForceTweaks.dll) bytes)"
